def expand(text, p):
    """Resolve {{include path}} and the post tokens inside a header or body fragment."""
    def include(m):
        path = ROOT / m.group(1).strip()
        if not path.is_file():
            sys.exit(f"build-blog.py: include not found: {m.group(1).strip()}")
        return path.read_text(encoding="utf-8")
    text = re.sub(r"\{\{include ([^}]+)\}\}", include, text)
    tokens = {"title": esc(p["title"]), "description": esc(p["description"]), "author": esc(p["author"]),
              "date": format_date(p["date"], p["lang"]), "minutes": str(reading_minutes(p["body"])),
              "category": esc(p["category"])}
    return re.sub(r"\{\{(title|description|author|date|minutes|category)\}\}", lambda m: tokens[m.group(1)], text)


def render_post(p):
    t = LANG[p["lang"]]
    og = SITE + p["og_image"] if p.get("og_image") else og_image(p)
    alternates = [(p["lang"], p["url"])] + ([(p["pair"]["lang"], p["pair"]["url"])] if p["pair"] else [])
    other = p["pair"]["url"] if p["pair"] else LANG["es" if p["lang"] == "en" else "en"]["blog_path"]
    jsonld = [
        {"@context": "https://schema.org", "@type": "BlogPosting", "headline": p["title"],
         "description": p["description"], "image": [og], "datePublished": p["date"],
         "dateModified": p.get("updated", p["date"]), "inLanguage": p["lang"],
         "author": {"@type": "Person", "name": p["author"]}, "publisher": publisher(),
         "mainEntityOfPage": f"{SITE}{p['url']}"},
        {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": t["home_crumb"], "item": f"{SITE}{t['home']}"},
            {"@type": "ListItem", "position": 2, "name": "Blog", "item": f"{SITE}{t['blog_path']}"},
            {"@type": "ListItem", "position": 3, "name": p["title"], "item": f"{SITE}{p['url']}"}]},
    ]
    extra = f'\n  <meta property="article:published_time" content="{p["date"]}" />'
    page = head(p["lang"], p.get("seo_title") or f"{p['title']} | Pegasus Global Trade", p["description"], p["url"], alternates, og,
                "noindex, follow" if p["draft"] else "index, follow", jsonld, "article", extra)
    # post stylesheets load after blog.css so they win ties
    blog_css = '<link rel="stylesheet" href="/assets/blog.css" />'
    page = page.replace(blog_css, blog_css + "".join(f'\n  <link rel="stylesheet" href="{href}" />' for href in p.get("css", [])))
    page += chrome_top(p["lang"], other)
    if p.get("header"):
        header_path = ROOT / p["header"]
        if not header_path.is_file():
            sys.exit(f"build-blog.py: header not found: {p['header']}")
        header = expand(header_path.read_text(encoding="utf-8"), p)
    else:
        header = f"""    <header class="article-head"><div class="inner">
      <div class="breadcrumbs"><a href="{t['home']}">{t['home_crumb']}</a> / <a href="{t['blog_path']}">Blog</a></div>
      <span class="kicker">{esc(p['category'])}</span>
      <h1>{esc(p['title'])}</h1>
      <p class="lead">{esc(p['description'])}</p>
      <div class="article-meta"><span>{esc(p['author'])}</span><span>{format_date(p['date'], p['lang'])}</span><span>{reading_minutes(p['body'])} {t['min_read']}</span></div>
    </div></header>
    <div class="article-cover"><img src="{p['cover']}" alt="{esc(p['cover_alt'])}" fetchpriority="high" /></div>
"""
    cta = "" if p.get("cta") is False else f"""    <aside class="article-cta"><div class="box">
      <h2>{t['cta_h']}</h2>
      <p>{t['cta_p']}</p>
      <a href="{esc(wa_link(t['cta_msg']))}" class="btn-wa" data-cta="blog" target="_blank" rel="noopener">{WA_ICON}<span>{t['cta_btn']}</span></a>
    </div></aside>
"""
    main_class = f' class="{esc(p["page_class"])}"' if p.get("page_class") else ""
    page += f"""  <main{main_class}>
{header}    <article class="article-body">
{expand(p['body'], p)}
    </article>
{cta}    <div class="article-foot"><a href="{t['blog_path']}">{t['back']}</a></div>
  </main>
"""
    return page + chrome_bottom(p["lang"], p.get("js", []))


def render_index(lang, posts):
    t = LANG[lang]
    other_lang = "es" if lang == "en" else "en"
    listed = sorted([p for p in posts if p["lang"] == lang], key=lambda p: p["date"], reverse=True)
    published = [p for p in listed if not p["draft"]]
    jsonld = {"@context": "https://schema.org", "@type": "Blog", "name": t["blog_title"],
              "description": t["blog_description"], "url": f"{SITE}{t['blog_path']}", "inLanguage": lang,
              "publisher": publisher(),
              "blogPost": [{"@type": "BlogPosting", "headline": p["title"], "url": f"{SITE}{p['url']}",
                            "datePublished": p["date"]} for p in published]}
    alternates = [(lang, t["blog_path"]), (other_lang, LANG[other_lang]["blog_path"])]
    page = head(lang, t["blog_title"], t["blog_description"], t["blog_path"], alternates,
                f"{SITE}/assets/og-image.jpg", "index, follow" if published else "noindex, follow", jsonld)
    page += chrome_top(lang, LANG[other_lang]["blog_path"])
    cards = "".join(f"""
      <a class="post-card" href="{p['url']}">
        <img src="{p['cover']}" alt="{esc(p['cover_alt'])}" loading="lazy" decoding="async" />
        <div class="post-card-body">
          <span class="cat">{esc(p['category'])}</span>
          <h2>{esc(p['title'])}</h2>
          <p>{esc(p['description'])}</p>
          <span class="meta">{format_date(p['date'], lang)} · {reading_minutes(p['body'])} {t['min_read']}</span>
        </div>
      </a>""" for p in listed)
    body = f'<div class="post-grid">{cards}\n    </div>' if listed else f'<p class="empty">{t["empty"]}</p>'
    page += f"""  <main>
    <header class="blog-head"><div class="wrap">
      <span class="kicker">{t['blog_kicker']}</span>
      <h1>{t['blog_h1']}</h1>
      <p>{t['blog_intro']}</p>
    </div></header>
    <div class="wrap">
    {body}
    </div>
  </main>
"""
    return page + chrome_bottom(lang)


def write(rel_dir, content):
    out = ROOT / rel_dir.lstrip("/") / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")


def remove_stale(posts):
    """Delete generated post folders whose slug no longer exists (only folders this script wrote)."""
    keep = {(ROOT / p["url"].lstrip("/")).resolve() for p in posts}
    for base in (ROOT / "blog", ROOT / "es" / "blog"):
        if not base.is_dir():
            continue
        for d in base.iterdir():
            idx = d / "index.html"
            if d.is_dir() and d.resolve() not in keep and idx.is_file() and GENERATED in idx.read_text(encoding="utf-8")[:400]:
                shutil.rmtree(d)
                print(f"removed stale {d.relative_to(ROOT)}")


def write_sitemap(posts):
    def entry(loc, alts, lastmod=None):
        links = "".join(f'\n    <xhtml:link rel="alternate" hreflang="{l}" href="{SITE}{u}" />' for l, u in alts)
        mod = f"\n    <lastmod>{lastmod}</lastmod>" if lastmod else ""
        return f"  <url>\n    <loc>{SITE}{loc}</loc>{mod}{links}\n  </url>"
    home_alts = [("en", "/"), ("es", "/es")]
    entries = [entry("/", home_alts), entry("/es", home_alts)]
    published = [p for p in posts if not p["draft"]]
    for lang in ("en", "es"):
        if any(p["lang"] == lang for p in published):
            entries.append(entry(LANG[lang]["blog_path"], [("en", "/blog"), ("es", "/es/blog")]))
    for p in published:
        alts = [(p["lang"], p["url"])]
        if p["pair"] and not p["pair"]["draft"]:
            alts.append((p["pair"]["lang"], p["pair"]["url"]))
        entries.append(entry(p["url"], alts, p.get("updated", p["date"])))
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(entries) + "\n</urlset>\n", encoding="utf-8")
    (ROOT / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n", encoding="utf-8")
    return len(entries)


