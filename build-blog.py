def esc(text):
    return html.escape(text, quote=True)


def wa_link(message):
    from urllib.parse import quote
    return "https://wa.me/573166541111?text=" + quote(message)


def format_date(iso, lang):
    d = datetime.date.fromisoformat(iso)
    if lang == "es":
        return f"{d.day} de {MONTHS_ES[d.month - 1]} de {d.year}"
    return d.strftime("%B ") + str(d.day) + d.strftime(", %Y")


def reading_minutes(body):
    words = len(re.sub(r"<[^>]+>", " ", body).split())
    return max(1, math.ceil(words / 220))


def load_posts():
    posts = []
    for path in sorted(SRC.glob("*.html")):
        m = re.fullmatch(r"(.+)\.(en|es)\.html", path.name)
        if not m:
            sys.exit(f"build-blog.py: {path.name} must be named <id>.en.html or <id>.es.html")
        text = path.read_text(encoding="utf-8")
        head = re.match(r"\s*<!--(.*?)-->(.*)", text, re.S)
        if not head:
            sys.exit(f"build-blog.py: {path.name} must start with a <!-- {{json}} --> block")
        try:
            meta = json.loads(head.group(1))
        except json.JSONDecodeError as e:
            sys.exit(f"build-blog.py: invalid JSON in {path.name}: {e}")
        missing = [k for k in REQUIRED if not meta.get(k)]
        if missing:
            sys.exit(f"build-blog.py: {path.name} is missing: {', '.join(missing)}")
        datetime.date.fromisoformat(meta["date"])
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", meta["slug"]):
            sys.exit(f"build-blog.py: slug in {path.name} must use lowercase letters, numbers and hyphens")
        lang = m.group(2)
        meta.update(id=m.group(1), lang=lang, body=head.group(2).strip(), draft=bool(meta.get("draft")),
                    url=f"{LANG[lang]['blog_path']}/{meta['slug']}")
        posts.append(meta)
    seen = set()
    for p in posts:
        if (p["lang"], p["slug"]) in seen:
            sys.exit(f"build-blog.py: duplicate {p['lang']} slug '{p['slug']}'")
        seen.add((p["lang"], p["slug"]))
    for p in posts:
        p["pair"] = next((q for q in posts if q["id"] == p["id"] and q["lang"] != p["lang"]), None)
    return posts


def og_image(post):
    """A 1200x630 JPEG next to the cover for link previews; falls back to the site image."""
    cover = ROOT / post["cover"].lstrip("/")
    if not cover.is_file():
        sys.exit(f"build-blog.py: cover not found: {post['cover']}")
    out = cover.with_name(cover.stem + "-og.jpg")
    try:
        from PIL import Image
    except ImportError:
        return f"{SITE}/assets/og-image.jpg"
    if not out.exists() or out.stat().st_mtime < cover.stat().st_mtime:
        im = Image.open(cover).convert("RGB")
        ratio = 1200 / 630
        if im.width / im.height > ratio:
            w = int(im.height * ratio); left = (im.width - w) // 2
            im = im.crop((left, 0, left + w, im.height))
        else:
            h = int(im.width / ratio); top = (im.height - h) // 2
            im = im.crop((0, top, im.width, top + h))
        im.resize((1200, 630), Image.LANCZOS).save(out, quality=86, optimize=True)
    return SITE + "/" + out.relative_to(ROOT).as_posix()


